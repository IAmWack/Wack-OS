/**
 * @file    sim_sound.c
 * @author  IAmWack
 * @brief   Реализация sound.h для ноутбука — подменяет пищалку печатью в терминал.
 *
 * Пищалки нет ни на макете, ни в окне — поэтому звуки просто
 * печатаются в терминал. Этого достаточно, чтобы видеть, в каких
 * местах интерфейс будет пикать, и не забыть убрать лишнее до того,
 * как пищалка появится (см. board_pins.h на master).
 */
#include "sound.h"

#include <stdio.h>

/* ============================================================================
 *  Static state
 * ============================================================================ */

static uint8_t s_volume = 6;

/* ============================================================================
 *  Public API
 * ============================================================================ */

/** @brief Инициализация звука (по интерфейсу sound.h). */
void sound_init(void)
{
    printf("[sim] звук: пищалки нет, играю в терминал\n");
}

/** @brief Задать громкость. @param level 0..10, значения выше 10 обрезаются. */
void sound_set_volume(uint8_t level)
{
    s_volume = (level > 10) ? 10 : level;
}

/** @brief Проиграть звук (в симуляторе — напечатать имя в терминал). @param id Идентификатор звука. */
void sound_play(sound_id_t id)
{
    static const char *NAMES[] = { "tick", "select", "back", "error", "boot" };
    if (s_volume == 0 || id == SOUND_TICK) {
        return; /* тиканье энкодера завалило бы весь лог */
    }
    printf("[sim] ♪ %s\n", NAMES[id]);
}
