/**
 * @file    sim_display.c
 * @author  IAmWack
 * @brief   Реализация display.h для ноутбука — подменяет ST7789 (SPI) X11-окном.
 *
 * Те же функции, что и в master/main/display.c: прошивка не видит
 * разницы, вызывает display_init()/display_set_brightness()/
 * display_flush() как обычно. Весь рендер до момента "куда уходит
 * кадр" — общий код wackos_gfx, здесь только последний шаг.
 */
#include "display.h"
#include "sim.h"

/* ============================================================================
 *  Static state
 * ============================================================================ */

static uint8_t s_brightness = 100;

/* ============================================================================
 *  Public API
 * ============================================================================ */

/**
 * @brief   Инициализация экрана (по интерфейсу display.h).
 *
 * Окно открывается в sim_main.c до запуска логики прошивки —
 * ui_init() зовёт display_init() уже "по факту".
 */
void display_init(void)
{
}

/**
 * @brief   Задать яркость подсветки.
 * @param   percent  0..100, значения выше 100 обрезаются.
 */
void display_set_brightness(uint8_t percent)
{
    s_brightness = (percent > 100) ? 100 : percent;
}

/**
 * @brief   Вывести кадровый буфер на экран (в окно X11).
 *
 * Подсветки у окна нет, поэтому яркость изображаем затемнением
 * кадра. На плате этим занимается ШИМ на PIN_LCD_BL, и кадр
 * остаётся нетронутым — разница только здесь.
 */
void display_flush(void)
{
    gfx_dim((uint8_t)(255 * s_brightness / 100));
    sim_window_present(gfx_framebuffer());
}
