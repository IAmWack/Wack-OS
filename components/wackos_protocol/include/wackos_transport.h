/*
 * Интерфейс транспорта для протокола Wack-OS.
 *
 * Это единственная точка, через которую слой протокола общается
 * с "внешним миром". Сам протокол не знает и не должен знать, что
 * за ней стоит UART, SPI или сокет — поэтому здесь нет ни одного
 * #include с железом.
 *
 * Каждая сторона (master/slave) подставляет свою реализацию этого
 * интерфейса (см. uart_transport.c в master/ и slave/).
 */
#pragma once

#include <stddef.h>
#include <stdint.h>

typedef struct {
    /*
     * Отправить len байт. Возвращает количество отправленных байт
     * либо отрицательное значение при ошибке.
     */
    int (*write)(const uint8_t *data, size_t len);

    /*
     * Прочитать один "кадр" построчно (до '\n' включительно) в buf,
     * не более max_len байт, ожидая не дольше timeout_ms миллисекунд.
     * Возвращает количество прочитанных байт (включая '\n'),
     * 0 — если данных не дождались (тайм-аут), <0 при ошибке транспорта.
     */
    int (*read_line)(uint8_t *buf, size_t max_len, uint32_t timeout_ms);
} wackos_transport_t;
