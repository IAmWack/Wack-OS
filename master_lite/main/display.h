/**
 * @file    display.h
 * @author  IAmWack
 * @brief   Публичный интерфейс слоя дисплея master.
 *
 * Знает про ST7789/SPI — и больше ни про что. Рисование сюда не входит:
 * весь рендер идёт в кадровый буфер wackos_gfx (components/wackos_gfx),
 * а display отвечает только за то, чтобы готовый кадр оказался на
 * матрице. Ровно по этой границе проходит подмена в симуляторе:
 * sim/sim_display.c реализует те же две функции, но выводит кадр в
 * окно на ноутбуке.
 */
#pragma once

#include "wackos_gfx.h"

/* ============================================================================
 *  Defines / Macros
 * ============================================================================ */

#define LCD_WIDTH  GFX_W
#define LCD_HEIGHT GFX_H

/* ============================================================================
 *  Public API
 * ============================================================================ */

/** @brief  Инициализировать SPI-шину, панель ST7789 и подсветку. */
void display_init(void);

/**
 * @brief   Яркость подсветки, 0..100 %.
 * @param   percent  Значение яркости (>100 обрезается до 100).
 *
 * На плате это ШИМ на PIN_LCD_BL, в симуляторе — затемнение кадра
 * (подсветки-то нет, а ползунок в настройках должен что-то делать).
 */
void display_set_brightness(uint8_t percent);

/** @brief  Отправить текущий кадровый буфер gfx на экран целиком. */
void display_flush(void);
