/**
 * @file    clock.h
 * @author  IAmWack
 * @brief   Программные "часы" (нет RTC-микросхемы на плате).
 *
 * Время затравливается временем сборки прошивки (__DATE__/__TIME__) и
 * дальше идёт штатным системным временем ESP-IDF — то есть и секунды
 * действительно тикают, просто после выключения питания (RTC не
 * backed-up батарейкой) при следующей прошивке время снова станет
 * временем сборки. clock_adjust_*() — ручная подстройка на экране
 * настроек, если после прошивки время разошлось с реальным.
 */
#pragma once

/* ============================================================================
 *  Public API
 * ============================================================================ */

/** @brief  Выставить системное время = время сборки прошивки. */
void clock_init(void);

/** @brief  Сдвинуть текущее время на delta часов (может быть отрицательным). */
void clock_adjust_hours(int delta);
/** @brief  Сдвинуть текущее время на delta минут (может быть отрицательным). */
void clock_adjust_minutes(int delta);

/** @brief  Сдвинуть текущую дату на delta дней (может быть отрицательным). */
void clock_adjust_days(int delta);
/** @brief  Сдвинуть текущий месяц на delta (может быть отрицательным). */
void clock_adjust_months(int delta);
/** @brief  Сдвинуть текущий год на delta (может быть отрицательным). */
void clock_adjust_years(int delta);
