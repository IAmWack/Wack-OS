/**
 * @file    board_pins.h
 * @author  IAmWack
 * @brief   Распиновка платы (ESP32-S3), ветка master_lite — без UART к slave.
 *
 * Единственное место, где эти номера упоминаются — остальной код
 * обращается к дисплею/энкодеру только через их модули (display.h,
 * encoder.h).
 */
#pragma once

/* ============================================================================
 *  Defines / Macros
 * ============================================================================ */

/* Экран ST7789, 172x320, SPI. Значения даны в задаче. */
#define PIN_LCD_MOSI  45
#define PIN_LCD_SCLK  40
#define PIN_LCD_CS    42
#define PIN_LCD_DC    41
#define PIN_LCD_RST   39
/*
 * ПОДТВЕРЖДЕНО НА ЖЕЛЕЗЕ: 46, не 48. Три сторонних источника (включая
 * офиц. демо Waveshare для этой платы) независимо указывали на 48 —
 * с ним подсветка не загоралась вообще ни при одной полярности/ШИМ. 46
 * нашёлся в отзывах на конкретно купленный товар и оказался верным —
 * видимо, другая ревизия/партия платы. Если будете сверяться с
 * документацией/чужим кодом по этой плате — перепроверяйте этот пин.
 */
#define PIN_LCD_BL    46

/* Энкодер KY-040. Пины не были заданы явно — поставлены условные,
 * уточните под свою разводку. Физически ручка пока не распаяна —
 * вместо неё временно рулит кнопка BOOT (см. PIN_BOOT_BTN, master/main/
 * boot_button.c); как только появится энкодер, в CMakeLists.txt
 * вернуть "encoder.c" вместо "boot_button.c", эти пины уже на месте. */
#define PIN_ENC_CLK   4
#define PIN_ENC_DT    5
#define PIN_ENC_SW    6

/* Временная замена энкодеру: штатная кнопка BOOT платы (GPIO0,
 * подтянута к питанию внешней обвязкой). Жест в boot_button.c: одно
 * короткое нажатие — пролистать вниз, два коротких подряд — вверх,
 * долгое — клик/выбор. */
#define PIN_BOOT_BTN  0

/* Пищалка. Её на макете ещё нет: -1 = не подключена, слой звука при
 * этом молчит (master/main/sound.c). Появится — поставить сюда номер
 * пина, больше ничего менять не нужно. */
#define PIN_BUZZER    -1

/*
 * Встроенный слот microSD платы Waveshare ESP32-S3-LCD-1.47, 4-битный
 * SDMMC (не SPI) — так распаян на плате, пины фиксированные, менять
 * не нужно. Сверено по официальной wiki/docs Waveshare и примеру
 * espp/ws-s3-lcd-1-47.
 */
#define PIN_SD_CLK    14
#define PIN_SD_CMD    15
#define PIN_SD_D0     16
#define PIN_SD_D1     18
#define PIN_SD_D2     17
#define PIN_SD_D3     21

/*
 * ADC-пин для чтения заряда батареи. VBAT с JST-разъёма платы идёт сюда
 * НАПРЯМУЮ, без делителя — батарея подобрана под эту плату специально
 * (пользователь подтвердил), так что внешний делитель не нужен. На
 * ESP32-S3 GPIO1 — это ADC1_CH0 (канал = номер пина минус 1, см.
 * battery.c). -1 означало бы "не подключено" (тот же приём, что у
 * PIN_BUZZER чуть выше) — тут уже боевое значение.
 */
#define PIN_BATTERY_ADC  1

/*
 * I2C-шина под будущие датчики (сейчас на очереди — акселерометр/гироскоп
 * MPU6050, см. mpu6050.c). -1 = физически ещё не распаяно: mpu6050_init()
 * тогда тихо не находит датчик (тот же приём, что у PIN_BUZZER/было у
 * PIN_BATTERY_ADC выше). Когда MPU6050 подгонят — впаять SDA/SCL на любую
 * свободную пару GPIO (годится любой пин, I2C на ESP32-S3 маршрутизируется
 * через GPIO-матрицу) и проставить тут реальные номера.
 */
#define PIN_I2C_SCL  -1
#define PIN_I2C_SDA  -1
