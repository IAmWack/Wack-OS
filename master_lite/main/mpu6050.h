/**
 * @file    mpu6050.h
 * @author  IAmWack
 * @brief   Акселерометр/гироскоп MPU6050 по I2C.
 */
#pragma once

#include <stdbool.h>

/* ============================================================================
 *  Types
 * ============================================================================ */

typedef struct {
    float accel_x, accel_y, accel_z; /* g */
    float gyro_x, gyro_y, gyro_z;    /* градусы/с */
} mpu6050_sample_t;

/* ============================================================================
 *  Public API
 * ============================================================================ */

/**
 * @brief   Поднять I2C и найти MPU6050 по WHO_AM_I.
 * @return  true, если датчик отозвался и готов к чтению.
 *
 * Ничего не делает и возвращает false, если PIN_I2C_SCL/PIN_I2C_SDA == -1
 * (см. board_pins.h) — датчик физически ещё не распаян.
 */
bool mpu6050_init(void);

/** @brief  Нашёлся ли датчик при mpu6050_init() — без этого mpu6050_read() смысла не имеет. */
bool mpu6050_present(void);

/**
 * @brief   Прочитать свежий замер акселерометра и гироскопа.
 * @param   out  Куда записать результат.
 * @return  true, если чтение по I2C прошло успешно.
 */
bool mpu6050_read(mpu6050_sample_t *out);
