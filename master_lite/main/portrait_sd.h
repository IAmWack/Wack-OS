/**
 * @file    portrait_sd.h
 * @author  IAmWack
 * @brief   Общий загрузчик растровых портретов маскотов с microSD.
 *
 * Все три маскота (Астольфо/Разор/Венти) вместе с BLE/NimBLE стеком не
 * влезали во флеш как C-таблицы (см. tools/gen_portraits.py, который
 * для этой платы больше не используется) — бинарники из
 * tools/portraits_sd_out (см. tools/gen_portraits_sd.py) лежат на
 * карте в /portraits/ и читаются сюда по требованию.
 */
#pragma once

#include <stdint.h>

/* ============================================================================
 *  Defines / Macros
 * ============================================================================ */

/* Должно совпадать с W,H в tools/gen_portraits_sd.py. */
#define PORTRAIT_SD_W 140
#define PORTRAIT_SD_H 190

/* ============================================================================
 *  Public API
 * ============================================================================ */

/**
 * @brief   Загрузить портрет "<character>_<mood>.bin" с карты в общий
 *          кэш-буфер (один на всю систему — одновременно показывается
 *          только один портрет).
 * @param   character  Имя персонажа, например "astolfo"/"razor"/"venti".
 * @param   mood       Имя настроения, например "idle"/"happy"/...
 * @return  Указатель на PORTRAIT_SD_W*PORTRAIT_SD_H пикселей RGB565,
 *          либо NULL, если карты/файла нет (вызывающий решает, что
 *          рисовать вместо портрета).
 *
 * Повторный вызов с теми же character/mood отдаёт закэшированный буфер
 * без обращения к карте — дорогая чтение-операция происходит только
 * при смене персонажа/настроения, не каждый кадр.
 */
const uint16_t *portrait_sd_load(const char *character, const char *mood);
