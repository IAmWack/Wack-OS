/**
 * @file    razor.h
 * @author  IAmWack
 * @brief   Публичный интерфейс персонажа-маскота Разора (второй маскот).
 *
 * Тот же принцип, что и у Астольфо (см. astolfo.h): не картинка, а
 * состояние системы, нарисованное примитивами wackos_gfx — ноль байт
 * ассетов. Второй маскот — задел под переключение "обычный/вооружённый
 * режим" (см. docs/SECURITY.md, SYS_ARM): предполагается, что в
 * вооружённом режиме на экране будет Разор вместо Астольфо, сигнализируя
 * "сейчас доступны особые команды" самим фактом смены персонажа.
 * Сама коммутация — дело app_logic/экранов, этот файл только рисует.
 */
#pragma once

#include <stdint.h>
#include <stdbool.h>

/* ============================================================================
 *  Defines / Macros
 * ============================================================================ */

/* Как и у Астольфо: h — высота головы, вся фигура целиком —
 * примерно RAZOR_BUST_H(h) по вертикали от y вниз. */
#define RAZOR_BUST_H(h) ((h) * 23 / 10)

/* ============================================================================
 *  Types
 * ============================================================================ */

typedef enum {
    RAZOR_IDLE = 0,  /* дышит, моргает */
    RAZOR_HAPPY,     /* получилось */
    RAZOR_SAD,       /* slave не ответил / ошибка */
    RAZOR_THINKING,  /* идёт запрос */
    RAZOR_SLEEP,     /* долго ничего не происходит */
} razor_mood_t;

/* ============================================================================
 *  Public API
 * ============================================================================ */

/** @brief  Установить текущее настроение персонажа. */
void         razor_set_mood(razor_mood_t mood);
/** @brief  Текущее настроение персонажа. */
razor_mood_t razor_mood(void);

/** @brief  Пользователь что-то сделал — сбросить таймер засыпания. */
void razor_note_activity(void);

/**
 * @brief   Раз в кадр: обновить настроение по прошедшему времени.
 * @param   now_ms  Текущее время в миллисекундах (монотонное).
 */
void razor_tick(uint32_t now_ms);

/** @brief  Реплика персонажа под текущее настроение — для облачка в меню. */
const char *razor_line(void);

/**
 * @brief   Нарисовать бюст Разора (голова, уши, мех, плечи).
 * @param   cx  Центр по X.
 * @param   y   Верх фигуры по Y.
 * @param   h   Высота головы — масштаб всей фигуры (см. RAZOR_BUST_H).
 * @param   t   Время в миллисекундах, для анимации (дыхание, моргание...).
 */
void razor_draw(int cx, int y, int h, uint32_t t);

/**
 * @brief   Нарисовать растровый портрет (см. wackos_portraits.h) вместо процедурного.
 * @param   cx, top_y     Центр по X и верх по Y — как у razor_draw().
 * @param   dst_w, dst_h  Размер на экране.
 *
 * Только для "крупного" контекста (сейчас — экран режима) — на мелких
 * размерах по-прежнему рисует razor_draw(), см. astolfo_draw_portrait().
 */
void razor_draw_portrait(int cx, int top_y, int dst_w, int dst_h);
