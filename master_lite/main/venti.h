/**
 * @file    venti.h
 * @author  IAmWack
 * @brief   Публичный интерфейс персонажа-маскота Венти (третий маскот).
 *
 * Состояние — тот же принцип, что у Астольфо/Разора (см. astolfo.h/
 * razor.h): настроение само переключает экраны по ходу дела, простой
 * уводит в sleep. Рисование — НЕ процедурное (в отличие от них):
 * запечённые растровые портреты по арту пользователя, см. venti.c.
 * Привязан к теме "мята" (theme.c, THEME_MASCOT_VENTI).
 */
#pragma once

#include <stdint.h>
#include <stdbool.h>

/* ============================================================================
 *  Defines / Macros
 * ============================================================================ */

/* Как и у остальных: h — высота головы, вся фигура целиком — примерно
 * VENTI_BUST_H(h) по вертикали от y вниз. */
#define VENTI_BUST_H(h) ((h) * 23 / 10)

/* ============================================================================
 *  Types
 * ============================================================================ */

typedef enum {
    VENTI_IDLE = 0,  /* дышит, моргает */
    VENTI_HAPPY,     /* получилось */
    VENTI_SAD,       /* ошибка */
    VENTI_THINKING,  /* идёт запрос/загрузка */
    VENTI_SLEEP,     /* долго ничего не происходит */
} venti_mood_t;

/* ============================================================================
 *  Public API
 * ============================================================================ */

/** @brief  Установить текущее настроение персонажа. */
void         venti_set_mood(venti_mood_t mood);
/** @brief  Текущее настроение персонажа. */
venti_mood_t venti_mood(void);

/** @brief  Пользователь что-то сделал — сбросить таймер засыпания. */
void venti_note_activity(void);

/**
 * @brief   Раз в кадр: обновить настроение по прошедшему времени.
 * @param   now_ms  Текущее время в миллисекундах (монотонное).
 */
void venti_tick(uint32_t now_ms);

/** @brief  Реплика персонажа под текущее настроение — для облачка в меню. */
const char *venti_line(void);

/**
 * @brief   Нарисовать бюст Венти (растровый портрет текущего настроения).
 * @param   cx  Центр по X.
 * @param   y   Верх фигуры по Y.
 * @param   h   Высота головы — масштаб всей фигуры (см. VENTI_BUST_H).
 * @param   t   Не используется (растр не дышит/не моргает) — остался
 *              для единообразия сигнатуры с astolfo_draw()/razor_draw().
 */
void venti_draw(int cx, int y, int h, uint32_t t);

/**
 * @brief   Нарисовать растровый портрет настроения крупнее.
 * @param   cx, top_y     Центр по X и верх по Y — как у venti_draw().
 * @param   dst_w, dst_h  Размер на экране.
 */
void venti_draw_portrait(int cx, int top_y, int dst_w, int dst_h);
