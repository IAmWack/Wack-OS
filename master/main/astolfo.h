/**
 * @file    astolfo.h
 * @author  IAmWack
 * @brief   Публичный интерфейс персонажа-маскота Астольфо.
 *
 * Астольфо — не картинка, а состояние системы. Рисуется кодом из
 * примитивов wackos_gfx: нет ни PNG, ни SD-карты, ни декодера — на
 * любой размер отрисуется чисто, и в прошивке это стоит ноль байт
 * ассетов. Настроение переключает логика (app_logic.c) по событиям
 * протокола (ответил slave -> happy, молчит -> sad, идёт запрос ->
 * thinking), а простой сам уводит его в sleep.
 */
#pragma once

#include <stdint.h>
#include <stdbool.h>

/* ============================================================================
 *  Defines / Macros
 * ============================================================================ */

/*
 * Нарисовать бюст: h — высота головы, всё остальное (волосы, коса,
 * плечи, плащ) считается от неё. Целиком фигура занимает примерно
 * ASTOLFO_BUST_H(h) по вертикали от y вниз.
 */
#define ASTOLFO_BUST_H(h) ((h) * 23 / 10)

/* ============================================================================
 *  Types
 * ============================================================================ */

typedef enum {
    ASTOLFO_IDLE = 0,  /* дышит, моргает */
    ASTOLFO_HAPPY,     /* получилось */
    ASTOLFO_SAD,       /* slave не ответил / ошибка */
    ASTOLFO_THINKING,  /* идёт запрос */
    ASTOLFO_SLEEP,     /* долго ничего не происходит */
} astolfo_mood_t;

/* ============================================================================
 *  Public API
 * ============================================================================ */

/** @brief  Установить текущее настроение персонажа. */
void           astolfo_set_mood(astolfo_mood_t mood);
/** @brief  Текущее настроение персонажа. */
astolfo_mood_t astolfo_mood(void);

/** @brief  Пользователь что-то сделал — сбросить таймер засыпания. */
void astolfo_note_activity(void);

/**
 * @brief   Раз в кадр: обновить настроение по прошедшему времени.
 * @param   now_ms  Текущее время в миллисекундах (монотонное).
 *
 * Возвращает happy/sad в idle через пару секунд и уводит в sleep после
 * долгого простоя.
 */
void astolfo_tick(uint32_t now_ms);

/**
 * @brief   Нарисовать бюст Астольфо.
 * @param   cx  Центр по X.
 * @param   y   Верх фигуры по Y.
 * @param   h   Высота головы — масштаб всей фигуры.
 * @param   t   Время в миллисекундах, для анимации.
 *
 * Один и тот же код рисует и маленького Астольфо в углу меню, и
 * большого на экране загрузки — разницу делает только h.
 */
void astolfo_draw(int cx, int y, int h, uint32_t t);

/** @brief  Реплика персонажа под текущее настроение — для облачка в меню. */
const char *astolfo_line(void);
