/**
 * @file    main.c
 * @author  IAmWack
 * @brief   Master (ESP32-S3): точка входа приложения.
 *
 * Собирает слои вместе и запускает главный цикл — сам ничего "не
 * решает", только связывает транспорт, протокол и интерфейс (см.
 * docs/ARCHITECTURE.md, "Слои кода").
 */
#include "wackos_protocol.h"
#include "uart_transport.h"
#include "ui.h"

/* ============================================================================
 *  Public API
 * ============================================================================ */

/**
 * @brief   Точка входа ESP-IDF: собрать слои и запустить главный цикл.
 */
void app_main(void)
{
    const wackos_transport_t *transport = uart_transport_init();
    wackos_proto_init(transport);

    ui_init();

    /*
     * Весь цикл — это кадр интерфейса плюс разбор события энкодера.
     * Логика (запросы к slave) вызывается изнутри экранов, поэтому
     * здесь больше ничего и не нужно.
     */
    while (1) {
        ui_tick();
    }
}
